// 解析当前生效的界面风格。
// 豪华界面（宇宙尽头的花园）开启时强制覆盖为 TK_COSMIC，
// 否则取主题装扮所绑定的 ThemeKind。
const ThemeStyle& curTheme() {
    if (rec.luxUnlocked && rec.luxOn) return THEMES[TK_COSMIC];
    int idx = rec.themeSkin;
    if (idx < 0 || idx >= SKIN_COUNT || SKINS[idx].type != 0) return THEMES[TK_QUANTUM];
    int k = SKINS[idx].style;
    if (k < 0 || k >= TK_COUNT) k = TK_QUANTUM;
    return THEMES[k];
}

