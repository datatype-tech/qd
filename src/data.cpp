// 注意：密钥随程序一起分发，这只提高提取门槛，不是绝对保密。
// 改协议文字的流程：编辑 tools/eula_master.txt -> 运行打包脚本重新生成
// text.bin -> 重新编译（网页版还需重跑 build_web.bat 打包进 .data）。
